"""Four persistent learned raw-key/value slots with StreamingLLM positions.

Physical attention uses relative distances within the recent window. Virtual
keys occupy positions0..3; the current query saturates at cache position1024.
The parallel path reproduces the eviction semantics of the streaming path.
"""
import types
import torch


def rotate(attention, tensor, positions):
    length=int(positions.max())+1
    cached=getattr(attention,'prefix_rope_cache',None)
    if cached is None or cached[0].shape[2]<length or cached[0].device!=tensor.device:
        cos,sin=attention.rotary_emb(tensor,seq_len=max(length,2048))
        cached=(cos.to(tensor.device),sin.to(tensor.device));attention.prefix_rope_cache=cached
    cos=cached[0].index_select(2,positions.long())
    sin=cached[1].index_select(2,positions.long())
    d=attention.rotary_ndims;rot=tensor[...,:d];left,right=rot.chunk(2,-1)
    return torch.cat((rot*cos+torch.cat((-right,left),-1)*sin,tensor[...,d:]),-1)


def attend(attention,q,k,v,query_indices,key_indices):
    """Joint softmax; exact local causality and fixed virtual RoPE positions."""
    slots=attention.virtual_keys.shape[1];recent=attention.virtual_capacity-slots
    # Real-real relative distances are invariant to a common RoPE translation.
    qr=rotate(attention,q,query_indices+slots);kr=rotate(attention,k,key_indices+slots)
    real=(qr@kr.transpose(-1,-2))*attention.norm_factor
    mask=(key_indices[None,:]<=query_indices[:,None]) & (query_indices[:,None]-key_indices[None,:]<=recent)
    real=real.masked_fill(~mask,-torch.inf)
    qm=rotate(attention,q,query_indices.clamp(max=recent)+slots)
    memory=rotate(attention,attention.virtual_keys[None],torch.arange(slots,device=q.device))
    virtual=(qm@memory.transpose(-1,-2))*attention.norm_factor
    scores=torch.cat((virtual,real),-1)
    weights=scores.softmax(-1).to(v.dtype)
    values=torch.cat((attention.virtual_values[None].expand(v.shape[0],-1,-1,-1),v),2)
    output=weights@values
    if getattr(attention,'observe_virtual',False):attention.last_virtual_weights=weights[...,:slots].detach()
    return output,weights


def forward(self,hidden_states,attention_mask=None,position_ids=None,head_mask=None,
            layer_past=None,use_cache=False,output_attentions=False,**kwargs):
    if layer_past is not None:raise ValueError('Use PrefixKVDecoder for streaming, not HF cached forward')
    if attention_mask is not None and torch.any(attention_mask!=0):raise ValueError('Padding is unsupported in this fixed-block pilot')
    if head_mask is not None:raise ValueError('Head masking is unsupported')
    b,n,_=hidden_states.shape
    q,k,v=self.query_key_value(hidden_states).view(b,n,self.num_attention_heads,3*self.head_size).permute(0,2,1,3).chunk(3,-1)
    indices=torch.arange(n,device=q.device)
    output,weights=attend(self,q,k,v,indices,indices)
    output=self.dense(output.transpose(1,2).reshape(b,n,-1))
    outputs=(output,None)
    if output_attentions:outputs+=(weights,)
    return outputs


@torch.no_grad()
def capture(model,prefix):
    """Capture raw per-layer K,V generated by four actual training-prefix tokens."""
    saved={};hooks=[]
    for index,layer in enumerate(model.gpt_neox.layers):
        attention=layer.attention
        def save(module,inputs,output,_index=index,_attention=attention):
            q,k,v=output.view(1,len(prefix),_attention.num_attention_heads,3*_attention.head_size).permute(0,2,1,3).chunk(3,-1)
            saved[_index]=(k[0].detach().clone(),v[0].detach().clone())
        hooks.append(attention.query_key_value.register_forward_hook(save))
    try:model.gpt_neox(prefix[None],use_cache=False)
    finally:
        for hook in hooks:hook.remove()
    return [saved[i] for i in range(len(model.gpt_neox.layers))]


def install(model,pairs,capacity=1024):
    for param in model.parameters():param.requires_grad_(False)
    for layer,(key,value) in zip(model.gpt_neox.layers,pairs):
        attention=layer.attention
        attention.virtual_keys=torch.nn.Parameter(key.clone())
        attention.virtual_values=torch.nn.Parameter(value.clone())
        attention.virtual_capacity=capacity
        attention.forward=types.MethodType(forward,attention)
    return model


class PrefixKVDecoder:
    def __init__(self,model,capacity=1024):
        self.model=model.eval();self.capacity=capacity
        self.slots=model.gpt_neox.layers[0].attention.virtual_keys.shape[1]
        if capacity<=self.slots:raise ValueError('Virtual slots count against cache capacity')
        self.cache=[None]*len(model.gpt_neox.layers)
        for layer in model.gpt_neox.layers:
            layer.attention.virtual_capacity=capacity;layer.attention.observe_virtual=True

    @torch.no_grad()
    def step(self,token):
        x=self.model.gpt_neox.embed_in(token.reshape(1,1))
        for i,layer in enumerate(self.model.gpt_neox.layers):
            a=layer.attention;z=layer.input_layernorm(x)
            q,k,v=a.query_key_value(z).view(1,1,a.num_attention_heads,3*a.head_size).permute(0,2,1,3).chunk(3,-1)
            if self.cache[i] is not None:
                k=torch.cat((self.cache[i][0],k),2);v=torch.cat((self.cache[i][1],v),2)
            keys=torch.arange(k.shape[2],device=x.device);query=keys[-1:]
            out,_=attend(a,q,k,v,query,keys)
            out=a.dense(out.transpose(1,2).reshape(1,1,-1))
            if self.model.config.use_parallel_residual:x=layer.mlp(layer.post_attention_layernorm(x))+out+x
            else:
                x=x+out;x=layer.mlp(layer.post_attention_layernorm(x))+x
            recent=self.capacity-self.slots
            self.cache[i]=(k[:,:,-recent:],v[:,:,-recent:])
        return self.model.embed_out(self.model.gpt_neox.final_layer_norm(x))[0,0]

    def usage(self):
        return torch.stack([layer.attention.last_virtual_weights[0,:,0] for layer in self.model.gpt_neox.layers])
